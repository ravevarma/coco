//! Release-size report and the 108,000,000-byte base-image gate.
//!
//! The base size is the space the installed read-only base system occupies
//! on its filesystem: every file rounded up to whole clusters, plus one
//! cluster per directory. Filesystem metadata (FATs, reserved sectors) and
//! unused partition capacity are reported separately. No compression is
//! involved: the files on the ESP are exactly what executes.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::artifacts::{Outputs, sha256};
use crate::{BASE_SIZE_LIMIT, Res, output};

struct FatGeometry {
    bytes_per_sector: u64,
    sectors_per_cluster: u64,
    reserved_sectors: u64,
    fats: u64,
    fat_sectors: u64,
    total_sectors: u64,
}

fn fat_geometry(img: &Path) -> Res<FatGeometry> {
    let mut bs = [0u8; 512];
    use std::io::Read;
    fs::File::open(img).and_then(|mut f| f.read_exact(&mut bs)).map_err(|e| format!("read boot sector: {e}"))?;
    let u16_at = |o: usize| u64::from(u16::from_le_bytes([bs[o], bs[o + 1]]));
    let u32_at = |o: usize| u64::from(u32::from_le_bytes([bs[o], bs[o + 1], bs[o + 2], bs[o + 3]]));
    if bs[510] != 0x55 || bs[511] != 0xAA || &bs[82..87] != b"FAT32" {
        return Err("ESP is not a FAT32 volume".into());
    }
    Ok(FatGeometry {
        bytes_per_sector: u16_at(11),
        sectors_per_cluster: u64::from(bs[13]),
        reserved_sectors: u16_at(14),
        fats: u64::from(bs[16]),
        fat_sectors: u32_at(36),
        total_sectors: u32_at(32),
    })
}

fn walk(dir: &Path, rel: &Path, files: &mut Vec<(PathBuf, u64)>, dirs: &mut u64) -> Res<()> {
    let mut entries: Vec<_> =
        fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))?.filter_map(Result::ok).collect();
    entries.sort_by_key(fs::DirEntry::file_name);
    for e in entries {
        let p = e.path();
        let r = rel.join(e.file_name());
        if p.is_dir() {
            *dirs += 1;
            walk(&p, &r, files, dirs)?;
        } else {
            files.push((r, e.metadata().map_err(|e| format!("stat: {e}"))?.len()));
        }
    }
    Ok(())
}

/// Writes `target/coco/size-report.{md,json}` and `docs/size-report.md`;
/// fails if the base exceeds [`BASE_SIZE_LIMIT`].
pub fn report(root: &Path, out: &Outputs) -> Res<String> {
    let geo = fat_geometry(&out.esp_img)?;
    let cluster = geo.bytes_per_sector * geo.sectors_per_cluster;
    let mut files = Vec::new();
    let mut dirs = 1; // root directory
    walk(&out.esp_dir, Path::new(""), &mut files, &mut dirs)?;
    let payload: u64 = files.iter().map(|(_, s)| s).sum();
    let allocated: u64 = files.iter().map(|(_, s)| s.div_ceil(cluster).max(1) * cluster).sum::<u64>() + dirs * cluster;
    let fat_meta = (geo.reserved_sectors + geo.fats * geo.fat_sectors) * geo.bytes_per_sector;
    let partition = geo.total_sectors * geo.bytes_per_sector;
    let disk_len = fs::metadata(&out.disk_img).map_err(|e| format!("stat disk: {e}"))?.len();
    let pass = allocated <= BASE_SIZE_LIMIT;
    let rustc = output(Command::new("rustc").arg("--version").current_dir(root))?;

    let mut md = String::new();
    let w = &mut md;
    let _ = writeln!(w, "# coco release size report\n");
    let _ = writeln!(w, "Generated by `cargo xtask build` from the real build artifacts. Do not edit.\n");
    let _ = writeln!(w, "- Toolchain: `{}`", rustc.trim());
    let _ = writeln!(w, "- Limit (installed read-only base): **{BASE_SIZE_LIMIT} bytes**");
    let _ = writeln!(
        w,
        "- Measured base (files rounded to {cluster}-byte clusters + {dirs} directory clusters): **{allocated} bytes** \
         ({:.4}% of limit) — **{}**",
        allocated as f64 * 100.0 / BASE_SIZE_LIMIT as f64,
        if pass { "PASS" } else { "FAIL" }
    );
    let _ = writeln!(w, "- Raw payload (sum of file sizes, uncompressed): {payload} bytes\n");
    let _ = writeln!(w, "| File on ESP | Bytes | Allocated | SHA-256 |");
    let _ = writeln!(w, "|---|---:|---:|---|");
    for (rel, s) in &files {
        let hash = sha256(&out.esp_dir.join(rel))?;
        let _ = writeln!(w, "| `{}` | {s} | {} | `{hash}` |", rel.display(), s.div_ceil(cluster).max(1) * cluster);
    }
    let _ = writeln!(w, "\n## Measured separately (not part of the base)\n");
    let _ = writeln!(w, "| Item | Bytes |");
    let _ = writeln!(w, "|---|---:|");
    let _ = writeln!(w, "| FAT32 metadata (reserved sectors + {} FATs) | {fat_meta} |", geo.fats);
    let _ = writeln!(w, "| ESP partition capacity | {partition} |");
    let _ = writeln!(w, "| GPT disk image (`coco.img`, sparse) | {disk_len} |");
    let _ = writeln!(w, "| User documents / caches / swap / data partition | 0 (none exist yet) |");
    let _ = writeln!(w, "| Optional browser package | not built (no package exists) |");
    let _ = writeln!(w, "| Optional Tor Browser package | not built (no package exists) |");
    let _ =
        writeln!(w, "\nImage hashes: `esp.img` `{}`, `coco.img` `{}`", sha256(&out.esp_img)?, sha256(&out.disk_img)?);

    let mut json = String::from("{\n");
    let _ = writeln!(
        json,
        "  \"limit_bytes\": {BASE_SIZE_LIMIT},\n  \"base_bytes\": {allocated},\n  \"payload_bytes\": {payload},"
    );
    let _ =
        writeln!(json, "  \"cluster_bytes\": {cluster},\n  \"fat_metadata_bytes\": {fat_meta},\n  \"pass\": {pass},");
    let _ = writeln!(json, "  \"files\": [");
    for (i, (rel, s)) in files.iter().enumerate() {
        let comma = if i + 1 < files.len() { "," } else { "" };
        let _ = writeln!(json, "    {{\"path\": \"{}\", \"bytes\": {s}}}{comma}", rel.display());
    }
    json.push_str("  ]\n}\n");

    fs::write(out.dir.join("size-report.md"), &md).map_err(|e| format!("write report: {e}"))?;
    fs::write(out.dir.join("size-report.json"), &json).map_err(|e| format!("write report: {e}"))?;
    fs::write(root.join("docs/size-report.md"), &md).map_err(|e| format!("write docs report: {e}"))?;
    if !pass {
        return Err(format!("base image {allocated} bytes exceeds the {BASE_SIZE_LIMIT}-byte limit"));
    }
    Ok(md)
}
