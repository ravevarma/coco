/// Replacement glyph for bytes outside printable ASCII.
const UNKNOWN: [u8; HEIGHT] = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F];

const fn pack(src: &str) -> [u8; HEIGHT] {
    let b = src.as_bytes();
    let mut rows = [0u8; HEIGHT];
    let mut row = 0;
    while row < HEIGHT {
        let mut col = 0;
        while col < WIDTH {
            // Rows are 5 cells plus one separator: index = row * 6 + col.
            if b[row * 6 + col] == b'#' {
                rows[row] |= 1 << (WIDTH - 1 - col);
            }
            col += 1;
        }
        row += 1;
    }
    rows
}

const fn build() -> [[u8; HEIGHT]; 95] {
    let mut out = [[0u8; HEIGHT]; 95];
    let mut i = 0;
    while i < 95 {
        let s = SOURCE[i].as_bytes();
        // Compile-time shape check: 7 rows of 5 cells separated by spaces.
        assert!(s.len() == 41, "glyph source must be 41 bytes");
        out[i] = pack(SOURCE[i]);
        i += 1;
    }
    out
}

static GLYPHS: [[u8; HEIGHT]; 95] = build();

/// Row bitmaps for `byte`.
#[must_use]
pub fn glyph(byte: u8) -> &'static [u8; HEIGHT] {
    match byte {
        0x20..=0x7E => GLYPHS.get(usize::from(byte - 0x20)).unwrap_or(&UNKNOWN),
        _ => &UNKNOWN,
    }
}
